import {test,expect} from '@playwright/test';
import {signIn} from './helpers';

test('individual login, admin assignment, employee work, API denial, CRM feedback and revocation',async({page,browser})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await signIn(page);
 let dashboard=await (await page.request.get('/api/dashboard')).json();
 if(!dashboard.accounts.some((a:any)=>a.is_demo&&a.state==='qualified')){
  const response=await page.request.post('/api/jobs',{data:{province:'QC',profile:'H01',mode:'demo',idempotency_key:'browser-assignment-'+crypto.randomUUID()}});
  expect(response.status()).toBe(200);
  await expect.poll(async()=>{dashboard=await (await page.request.get('/api/dashboard')).json();return dashboard.accounts.some((a:any)=>a.is_demo&&a.state==='qualified')}).toBeTruthy();
 }
 const account=dashboard.accounts.find((a:any)=>a.name.startsWith('DEMO QC H01 HVAC 1'))||dashboard.accounts.find((a:any)=>a.is_demo&&a.state==='qualified');
 expect(account).toBeTruthy();
 expect((await page.request.put('/api/admin/users/nexa-demo:sales/grants',{data:{permission:'ai.work.summary',enabled:true,reason:'Prepare this explicitly authorized browser journey.'}})).status()).toBe(200);
 await page.getByRole('navigation').getByRole('button',{name:'企业管理'}).click();
 await page.getByText('分配客户与工作任务',{exact:true}).click();
 await page.getByRole('combobox',{name:'分配客户',exact:true}).selectOption(account.id);
 await page.getByRole('combobox',{name:'销售员工',exact:true}).selectOption('nexa-demo:sales');
 const instruction='确认已分配项目的执行进度，并回写工作结果。';
 await page.getByLabel('工作要求',{exact:true}).fill(instruction);
 const responsePromise=page.waitForResponse(r=>r.url().endsWith('/api/admin/assignments')&&r.request().method()==='POST');
 await page.getByRole('button',{name:'审核并分配工作'}).click();
 const assignment=await (await responsePromise).json();
 await expect(page.getByRole('status')).toContainText('客户工作已分配');
 await page.getByText('用户与功能权限',{exact:true}).click();
 const user=page.locator('.user-permission-row').filter({has:page.getByText('sales',{exact:false})}).filter({has:page.getByText('批量线索研究、ICP 配置与潜客库导出权限固定关闭。',{exact:true})});
 const permissionResponse=page.waitForResponse(r=>r.url().includes('/admin/users/nexa-demo:sales/grants')&&r.request().method()==='PUT');
 await user.getByRole('checkbox',{name:'工作摘要',exact:true}).click();
 expect((await permissionResponse).status()).toBe(200);
 await expect(page.getByRole('status')).toContainText('功能权限已更新');
 await expect(user.getByRole('checkbox',{name:'工作摘要',exact:true})).not.toBeChecked();
 await user.getByRole('checkbox',{name:'工作摘要',exact:true}).click();
 await expect(page.getByRole('status')).toContainText('功能权限已更新');
 await expect(user.getByRole('checkbox',{name:'工作摘要',exact:true})).toBeChecked();
 await page.getByText('用户与功能权限',{exact:true}).click();
 await page.getByText('AI Usage Policy · 模型、配额与费用',{exact:true}).click();
 await expect(page.getByLabel('企业月预算（USD）',{exact:true})).toHaveValue('300');
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.screenshot({path:'../.local/v3.3-admin-console.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
 await page.setViewportSize({width:1280,height:720});
 const context=await browser.newContext();const employee=await context.newPage();
 employee.on('pageerror',e=>errors.push(e.message));await signIn(employee,'sales');
 await expect(employee.getByRole('heading',{name:'我的任务，清晰可见。'})).toBeVisible();
 await expect(employee.getByRole('navigation')).toContainText('我的任务');
 await expect(employee.getByRole('navigation')).not.toContainText('客户研究');
 await expect(employee.getByRole('navigation')).not.toContainText('企业管理');
 await employee.getByTestId('assigned-task-'+assignment.task_id).click();
 await expect(employee.locator('.work-fields')).toContainText(account.name);
 await expect(employee.locator('.work-fields')).not.toContainText('@');
 const work='已记录项目进展，等待管理端审核下一步。';
 await employee.getByLabel('工作记录',{exact:true}).fill(work);
 await employee.getByRole('button',{name:'保存工作记录',exact:true}).click();
 await expect(employee.getByRole('status')).toContainText('统一 CRM');
 await employee.getByRole('button',{name:'标记任务完成'}).click();
 await expect(employee.getByTestId('assigned-task-'+assignment.task_id)).toContainText('已完成');
 await employee.evaluate(()=>window.scrollTo(0,0));
 await employee.screenshot({path:'../.local/v3.3-employee-app.png',fullPage:true});
 for(const path of ['/api/dashboard','/api/export','/api/admin/usage','/api/accounts/'+account.id]){
  expect((await employee.request.get(path)).status()).toBe(403);
 }
 expect((await employee.request.post('/api/assistant/tools/research',{data:{province:'QC',profile:'H01',mode:'demo',idempotency_key:'browser-escalation'}})).status()).toBe(403);
 expect((await employee.request.post('/api/webhooks/n8n',{data:{}})).status()).toBe(403);
 await employee.goto('/admin');await expect(employee).toHaveURL(/\/employee$/);
 await employee.getByRole('navigation').getByRole('button',{name:'AI 工作助手'}).click();
 await employee.getByRole('combobox',{name:'工作任务',exact:true}).selectOption(assignment.task_id);
 await employee.getByRole('textbox',{name:'工作指令',exact:true}).fill('帮我找 2,000 家 HVAC 公司');
 await employee.getByRole('button',{name:'运行工作助手'}).click();
 await expect(employee.locator('.alert.error')).toContainText('尚未获得授权');
 await employee.getByRole('textbox',{name:'工作指令',exact:true}).fill('整理这项工作的执行记录');
 await employee.getByRole('combobox',{name:'功能',exact:true}).selectOption('work_summary');
 await employee.getByRole('button',{name:'运行工作助手'}).click();
 await expect(employee.locator('.assistant-result')).toContainText('已记录');
 await page.getByRole('navigation').getByRole('button',{name:'企业管理'}).click();
 const record=page.getByTestId('assignment-'+assignment.id);
 await expect(record).toContainText(work,{timeout:10000});
 await expect(record).toContainText('已完成');
 await record.getByRole('button',{name:'撤回分配'}).click();
 await expect(page.getByRole('status')).toContainText('分配已撤回');
 expect((await employee.request.get('/api/work/tasks/'+assignment.task_id)).status()).toBe(404);
 expect(errors).toEqual([]);await context.close();
});

